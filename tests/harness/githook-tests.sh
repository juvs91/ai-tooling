#!/usr/bin/env bash
# tests/harness/githook-tests.sh — tools/install_hooks.sh --check, migración vía
# auto-sync-daily, doctor y task-verify (ADR-0074). Fixtures git reales.
set -uo pipefail

AI_TOOLING="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
INST="$AI_TOOLING/tools/install_hooks.sh"
T=$(mktemp -d); T=$(cd -P "$T" && pwd -P)
PASS=0; FAIL=0
ok()  { PASS=$((PASS+1)); echo "  ✓ $1"; }
bad() { FAIL=$((FAIL+1)); echo "  ✗ FAIL: $1"; }
eq()  { [ "$2" = "$3" ] && ok "$1" || bad "$1 (got [$2] want [$3])"; }
unset GIT_DIR GIT_INDEX_FILE CLAUDE_PROJECT_DIR AI_TOOLING_HOME CLAUDE_CODE_SESSION_ID
g() { git -c user.name=t -c user.email=t@t -c commit.gpgsign=false "$@"; }

OLD_PC='#!/usr/bin/env bash
# ai-tooling:adr-gate — ADR gate pre-commit hook (NO BORRAR ESTA LÍNEA)
COMMIT_MSG=$(cat .git/COMMIT_EDITMSG)'
OLD_BLOCK='# --- BEGIN ai-tooling:adr-gate (appended by install_hooks.sh) ---
COMMIT_MSG=$(cat .git/COMMIT_EDITMSG 2>/dev/null || true)
# --- END ai-tooling:adr-gate ---'
FW='#!/usr/bin/env bash
# File generated by pre-commit: https://pre-commit.com
# ID: 138fd403232d2ddd5efb44317e38bf03
exec true'

repo() {  # repo nuevo con checker; imprime su path (mktemp: corre dentro de $(…))
  local d; d=$(mktemp -d "$T/r.XXXX")
  mkdir -p "$d/tools" && (cd "$d" && g init -q && cp "$AI_TOOLING/tools/check_adr_gate.py" tools/ && g add -A && g commit -qm i)
  echo "$d"
}
chk() { (cd "$1" && bash "$INST" --check >/dev/null 2>&1); echo $?; }
inst() { (cd "$1" && bash "$INST" >/dev/null 2>&1); echo $?; }
hooks() { echo "$1/.git/hooks"; }

echo "══ G1: clasificación --check ══"
R=$(repo); eq "sin hook → 12" "$(chk "$R")" 12
eq "instalación → exit 0" "$(inst "$R")" 0
eq "después de instalar → 10" "$(chk "$R")" 10
echo "# tocado" >> "$(hooks "$R")/commit-msg"; eq "commit-msg propio alterado → 11" "$(chk "$R")" 11

R=$(repo); printf '%s\n' "$OLD_PC" > "$(hooks "$R")/pre-commit"
eq "OLD_BANNER en pre-commit → 11" "$(chk "$R")" 11
inst "$R" >/dev/null
[ ! -f "$(hooks "$R")/pre-commit" ] && [ -f "$(hooks "$R")/pre-commit.bak" ] && ok "pre-commit viejo migrado con .bak" || bad "pre-commit viejo no migrado / sin .bak"
eq "migrado → 10" "$(chk "$R")" 10

R=$(repo); { echo '#!/bin/sh'; echo 'echo ajeno'; printf '%s\n' "$OLD_BLOCK"; } > "$(hooks "$R")/pre-commit"
eq "bloque viejo en pre-commit ajeno → 11" "$(chk "$R")" 11
inst "$R" >/dev/null
grep -q 'echo ajeno' "$(hooks "$R")/pre-commit" && ! grep -q 'BEGIN ai-tooling' "$(hooks "$R")/pre-commit" \
  && ok "bloque quitado, hook ajeno preservado" || bad "migración del bloque incorrecta"

R=$(repo); printf '%s\n' "$FW" > "$(hooks "$R")/commit-msg"; eq "framework en commit-msg → 13" "$(chk "$R")" 13
R=$(repo); (cd "$R" && g config core.hooksPath .githooks); eq "core.hooksPath → 13" "$(chk "$R")" 13
eq "core.hooksPath: instalación exit 0" "$(inst "$R")" 0
[ ! -e "$R/.githooks/commit-msg" ] && ok "core.hooksPath: no escribe" || bad "escribió en hooksPath"
R=$(repo); rm "$R/tools/check_adr_gate.py"; eq "sin checker → 13" "$(chk "$R")" 13
mkdir -p "$T/nogit"; eq "no es repo git → 13" "$(chk "$T/nogit")" 13

R=$(repo); printf 'repos:\n  - repo: local\n    hooks:\n      - id: adr-gate\n' > "$R/.pre-commit-config.yaml"
OUT=$(cd "$R" && bash "$INST" --check 2>&1); RC=$?
eq "config con adr-gate sin framework → 12" "$RC" 12
grep -q 'pre-commit install' <<< "$OUT" && ok "mensaje sugiere pre-commit install" || bad "mensaje sin pre-commit install"
printf '%s\n' "$FW" > "$(hooks "$R")/pre-commit"; eq "framework pre-commit + id adr-gate → 13" "$(chk "$R")" 13

R=$(repo); printf '%s\n' "$FW" > "$(hooks "$R")/pre-commit"; inst "$R" >/dev/null
eq "framework solo-lint + nuestro commit-msg → 10 (no 13)" "$(chk "$R")" 10
R=$(repo); printf '%s\n' "$FW" > "$(hooks "$R")/pre-commit"; printf 'hooks:\n  # - id: adr-gate\n' > "$R/.pre-commit-config.yaml"
eq "id comentado no cuenta → 12" "$(chk "$R")" 12

R=$(repo); { printf '%s\n' "$FW"; printf '%s\n' "$OLD_BLOCK"; } > "$(hooks "$R")/pre-commit"
printf 'hooks:\n  - id: adr-gate\n' > "$R/.pre-commit-config.yaml"
eq "framework pre-commit con bloque viejo → 11" "$(chk "$R")" 11
inst "$R" >/dev/null; eq "limpiado una vez → 13" "$(chk "$R")" 13

R=$(repo); printf 'import sys\nprint("usage: x")\n' > "$R/tools/check_adr_gate.py"
eq "checker incompatible: instalación exit 0" "$(inst "$R")" 0
[ ! -f "$(hooks "$R")/commit-msg" ] && ok "preflight: no instala con checker incompatible" || bad "instaló con checker incompatible"

echo "══ G2: auto-sync migra solo instalaciones previas ══"
consumer() { local d; d=$(repo); mkdir -p "$d/.claude"
  echo "{\"local_path\":\"$AI_TOOLING\",\"sync_skills\":false,\"sync_hooks\":false,\"sync_doclens\":false${1:+,$1}}" > "$d/.ai-tooling"; echo "$d"; }
async() { echo "{\"cwd\":\"$1\"}" | (cd "$1" && CLAUDE_PROJECT_DIR="$1" ${2:+AI_TOOLING_HOME="$2"} bash "$AI_TOOLING/.claude/hooks/auto-sync-daily.sh" >/dev/null 2>&1); }
C=$(consumer); { echo '#!/bin/sh'; echo 'echo ajeno'; printf '%s\n' "$OLD_BLOCK"; } > "$(hooks "$C")/pre-commit"
async "$C"
eq "caso 11 → migrado" "$(chk "$C")" 10
grep -q 'echo ajeno' "$(hooks "$C")/pre-commit" && ok "pre-commit ajeno preservado" || bad "pre-commit ajeno perdido"
ls -d "$C"/.claude/.harness-backup-*-githooks >/dev/null 2>&1 && ok "respaldo de hooks git creado" || bad "sin respaldo de hooks git"
CK=$(cksum < "$(hooks "$C")/commit-msg"); async "$C"
eq "segunda corrida sin cambios" "$(cksum < "$(hooks "$C")/commit-msg")" "$CK"
C=$(consumer); async "$C"
[ ! -f "$(hooks "$C")/commit-msg" ] && ok "caso 12 → no instala" || bad "caso 12 instaló el gate"
grep -q 'git-hooks:.*no instalado' "$C/.claude/sync.log" && ok "caso 12 → queda en el log" || bad "caso 12 sin log"
C=$(consumer '"sync_git_hooks":false'); printf '%s\n' "$OLD_PC" > "$(hooks "$C")/pre-commit"; async "$C"
grep -q 'ai-tooling:adr-gate' "$(hooks "$C")/pre-commit" && ok "sync_git_hooks:false → no toca" || bad "sync_git_hooks:false migró"
OLDTB="$T/oldtoolbox"; mkdir -p "$OLDTB/tools"
git -C "$AI_TOOLING" show 750b7a3:tools/install_hooks.sh > "$OLDTB/tools/install_hooks.sh"
C=$(consumer); async "$C" "$OLDTB"
[ ! -f "$(hooks "$C")/commit-msg" ] && ok "toolbox viejo (sin --check) no se usa: no escribe" || bad "toolbox viejo instaló"

echo "══ G3: doctor y task-verify avisan sin escribir ══"
C=$(consumer); OUT=$(bash "$AI_TOOLING/scripts/harness-doctor.sh" "$C" 2>&1)
grep -q 'WARN: ADR gate git' <<< "$OUT" && ok "doctor avisa caso 12" || bad "doctor no avisa"
C=$(consumer); cp "$OLDTB/tools/install_hooks.sh" "$C/tools/install_hooks.sh"
echo '{}' > "$C/.ai-tooling"   # sin local_path → candidato = copia vieja del repo
bash "$AI_TOOLING/scripts/harness-doctor.sh" "$C" >/dev/null 2>&1
[ ! -f "$(hooks "$C")/commit-msg" ] && ok "doctor no usa la copia vieja (no escribe)" || bad "doctor instaló vía copia vieja"
C=$(consumer); mkdir -p "$C/.claude/hooks" "$C/.claude/sessions" "$C/scripts"
cp "$AI_TOOLING/.claude/hooks/task-scope-lib.sh" "$C/.claude/hooks/"; cp "$AI_TOOLING/scripts/task-verify.sh" "$C/scripts/"
echo '{"mode":"full","completion_checklist":["echo ok"]}' > "$C/.claude/sessions/sidg-task-scope.json"
OUT=$(cd "$C" && CLAUDE_CODE_SESSION_ID=sidg bash scripts/task-verify.sh 2>&1)
grep -q 'ADR gate git' <<< "$OUT" && ok "task-verify avisa caso 12" || bad "task-verify no avisa"
[ ! -f "$(hooks "$C")/commit-msg" ] && ok "task-verify no escribe" || bad "task-verify instaló"

echo ""
echo "══ Git hooks: $PASS ok, $FAIL fallos ══"
rm -rf "$T"
[ "$FAIL" -eq 0 ]
