#!/usr/bin/env bash
# supports: --check
# install_hooks.sh — Instala el git hook ADR gate (commit-msg)
#
# Uso:
#   bash tools/install_hooks.sh          instala / migra (idempotente; exit 0 = ok o no aplica)
#   bash tools/install_hooks.sh --check  solo lectura; clasifica el estado (ADR-0074):
#       10  al día
#       11  requiere migración (instalación vieja en pre-commit, o commit-msg propio desactualizado)
#       12  falta (no hay rastro del gate)
#       13  no aplica (no es git, core.hooksPath, sin tools/check_adr_gate.py, o el
#           framework pre-commit gestiona el gate)
#       otro (14 = error inesperado vía trap ERR) → error; los llamadores solo lo loguean
#     Imprime una línea con el motivo. La línea "# supports: --check" de arriba la
#     usan los llamadores para no invocar una versión vieja (que ignoraría --check
#     e instalaría).
#
# Hooks instalados:
#   commit-msg — ADR gate: bloquea commits que modifiquen rutas guardadas
#                sin un nuevo ADR-*.md staged junto al cambio.
#
# ADR-0073:
#   - Directorio de hooks por `git rev-parse --git-path hooks`: correcto en
#     worktrees (.git es un archivo ahí).
#   - commit-msg en vez de pre-commit: pre-commit corre ANTES de que git escriba
#     COMMIT_EDITMSG, así que leía el mensaje del commit ANTERIOR. commit-msg
#     recibe el mensaje real en $1. Las instalaciones previas en pre-commit se migran.
#   - Un hook ajeno se preserva: solo se reescribe el archivo si es nuestro
#     (línea de banner completa); si no, se agrega/actualiza un bloque BEGIN/END.
# ADR-0074:
#   - --check y la instalación comparten UNA clasificación (classify).
#   - core.hooksPath definido → no aplica (no se escribe en dirs ajenos/trackeados).
#   - Framework pre-commit gestionando el gate → no aplica; usado solo para lint
#     (pre-commit sin `id: adr-gate`) → se clasifica nuestro commit-msg normal.
#   - Antes de borrar/reescribir un hook se deja un .bak junto a él.

MODE="install"
[ "${1:-}" = "--check" ] && MODE="check"

set -Eeuo pipefail
[ "$MODE" = "check" ] && trap 'exit 14' ERR

BANNER="# ai-tooling:adr-gate — ADR gate commit-msg hook (NO BORRAR ESTA LÍNEA)"
OLD_BANNER="# ai-tooling:adr-gate — ADR gate pre-commit hook (NO BORRAR ESTA LÍNEA)"
BLOCK_BEGIN="# --- BEGIN ai-tooling:adr-gate (appended by install_hooks.sh) ---"
BLOCK_END="# --- END ai-tooling:adr-gate ---"
FRAMEWORK_MARK="File generated by pre-commit"
ADR_GATE_ID_RE="^[[:space:]]*(-[[:space:]]+)?id:[[:space:]]*[\"']?adr-gate[\"']?[[:space:]]*(#.*)?$"

# Cuerpo común: corre desde el toplevel del worktree actual; si la rama no
# tiene el checker (rama vieja), no bloquea.
GATE_BODY='(
  cd "$(git rev-parse --show-toplevel)" || exit 0
  [ -f tools/check_adr_gate.py ] || exit 0
  STAGED=$(git diff --cached --name-only 2>/dev/null || true)
  NEW_FILES=$(git diff --cached --name-only --diff-filter=A 2>/dev/null || true)
  COMMIT_MSG=$(grep -v "^#" "$1" 2>/dev/null || true)
  PYTHON_BIN="python3"; command -v python3 >/dev/null 2>&1 || PYTHON_BIN="python"
  "$PYTHON_BIN" tools/check_adr_gate.py \
    --changed-files "$STAGED" \
    --new-files     "$NEW_FILES" \
    --commit-message "$COMMIT_MSG"
) || exit $?'

HOOK_FILE_CONTENT="#!/usr/bin/env bash
$BANNER
# Bloquea commits que modifiquen rutas guardadas sin un nuevo ADR staged.
# Instalado por tools/install_hooks.sh — re-ejecuta para actualizar.
set -uo pipefail
$GATE_BODY"

# ── Entorno ──────────────────────────────────────────────────────────────────
if ! git rev-parse --git-dir >/dev/null 2>&1; then
  if [ "$MODE" = "check" ]; then echo "13 no es un repo git"; exit 13; fi
  echo "[ai-tooling:hooks] ERROR: no es un repo git." >&2
  exit 1
fi
REPO_ROOT="$(git rev-parse --show-toplevel)"
HOOKS_PATH_CFG="$(git config --get core.hooksPath || true)"
# --path-format=absolute exige git ≥2.31; --git-path (≥2.5) es relativo al cwd
HOOKS_DIR="$(git rev-parse --git-path hooks)"
case "$HOOKS_DIR" in /*) ;; *) HOOKS_DIR="$PWD/$HOOKS_DIR" ;; esac
COMMIT_MSG_HOOK="$HOOKS_DIR/commit-msg"
PRE_COMMIT="$HOOKS_DIR/pre-commit"
PC_CONFIG="$REPO_ROOT/.pre-commit-config.yaml"

_has_line()  { [ -f "$1" ] && grep -qxF -- "$2" "$1"; }
_has_text()  { [ -f "$1" ] && grep -qF -- "$2" "$1"; }
_config_declares_gate() { [ -f "$PC_CONFIG" ] && grep -qE -- "$ADR_GATE_ID_RE" "$PC_CONFIG"; }
_block_of() { awk -v b="$BLOCK_BEGIN" -v e="$BLOCK_END" '$0==e{f=0} f{print} $0==b{f=1}' "$1"; }
_precommit_traces() { _has_line "$PRE_COMMIT" "$OLD_BANNER" || _has_line "$PRE_COMMIT" "$BLOCK_BEGIN"; }
_framework_manages() {
  _has_text "$COMMIT_MSG_HOOK" "$FRAMEWORK_MARK" && return 0
  _has_text "$PRE_COMMIT" "$FRAMEWORK_MARK" && _config_declares_gate && return 0
  return 1
}

# classify → imprime "<código> <motivo>" (el código va por stdout, no como
# retorno: con set -E un retorno ≠ 0 dispararía el trap)
classify() {
  if [ -n "$HOOKS_PATH_CFG" ]; then echo "13 core.hooksPath=$HOOKS_PATH_CFG (gestionado fuera de .git/hooks)"; return 0; fi
  if [ ! -f "$REPO_ROOT/tools/check_adr_gate.py" ]; then echo "13 sin tools/check_adr_gate.py"; return 0; fi
  if _precommit_traces; then echo "11 instalación vieja del ADR gate en pre-commit"; return 0; fi
  if _framework_manages; then echo "13 el framework pre-commit gestiona el ADR gate"; return 0; fi
  if _has_line "$COMMIT_MSG_HOOK" "$BANNER"; then
    if [ -x "$COMMIT_MSG_HOOK" ] && cmp -s "$COMMIT_MSG_HOOK" <(printf '%s\n' "$HOOK_FILE_CONTENT"); then
      echo "10 commit-msg al día"
    else
      echo "11 commit-msg propio desactualizado"
    fi
    return 0
  fi
  if _has_line "$COMMIT_MSG_HOOK" "$BLOCK_BEGIN"; then
    if [ "$(_block_of "$COMMIT_MSG_HOOK")" = "$GATE_BODY" ]; then
      echo "10 bloque ADR gate al día en commit-msg ajeno"
    else
      echo "11 bloque ADR gate desactualizado en commit-msg ajeno"
    fi
    return 0
  fi
  if _config_declares_gate; then
    echo "12 .pre-commit-config.yaml declara adr-gate pero el framework no está instalado: corre 'pre-commit install --hook-type commit-msg' (no instales además el hook crudo: correría dos veces)"
    return 0
  fi
  echo "12 ADR gate git no instalado: bash tools/install_hooks.sh"
}

RESULT="$(classify)"
CODE="${RESULT%% *}"

if [ "$MODE" = "check" ]; then
  echo "$RESULT"
  exit "$CODE"
fi

# ── Instalación ──────────────────────────────────────────────────────────────
case "$CODE" in
  13)
    case "$RESULT" in
      *hooksPath*|*check_adr_gate*)
        echo "[ai-tooling:hooks] No se instala: ${RESULT#* }" >&2
        exit 0 ;;
    esac ;;
esac

# Preflight: el checker del repo debe aceptar --commit-message
if ! grep -q -- --commit-message <<<"$(cd "$REPO_ROOT" && python3 tools/check_adr_gate.py --help 2>&1 || true)"; then
  echo "[ai-tooling:hooks] WARN: tools/check_adr_gate.py no acepta --commit-message (versión incompatible) — no se instala." >&2
  exit 0
fi

mkdir -p "$HOOKS_DIR"

_backup() { [ -f "$1" ] && cp -p "$1" "$1.bak"; return 0; }
_strip_block() {
  local f="$1" tmp
  tmp="$(mktemp "$f.XXXXXX")"
  awk -v b="$BLOCK_BEGIN" -v e="$BLOCK_END" '$0==b{skip=1;next} $0==e{skip=0;next} !skip' "$f" > "$tmp"
  cat "$tmp" > "$f"; rm -f "$tmp"
}

# Limpieza de rastros en pre-commit: SIEMPRE (también si el framework gestiona el gate)
if _has_line "$PRE_COMMIT" "$OLD_BANNER"; then
  _backup "$PRE_COMMIT"; rm -f "$PRE_COMMIT"
  echo "[ai-tooling:hooks] Migrado: eliminado el ADR gate de pre-commit (respaldo: pre-commit.bak)"
elif _has_line "$PRE_COMMIT" "$BLOCK_BEGIN"; then
  _backup "$PRE_COMMIT"; _strip_block "$PRE_COMMIT"
  echo "[ai-tooling:hooks] Migrado: quitado el bloque ADR gate de $PRE_COMMIT (hook ajeno preservado)"
fi

# El framework gestiona el gate: no escribir commit-msg; quitar un bloque muerto
# que una versión previa haya dejado tras su `exec`.
if _framework_manages; then
  if _has_line "$COMMIT_MSG_HOOK" "$BLOCK_BEGIN"; then
    _backup "$COMMIT_MSG_HOOK"; _strip_block "$COMMIT_MSG_HOOK"
    echo "[ai-tooling:hooks] Quitado bloque muerto del commit-msg del framework"
  fi
  echo "[ai-tooling:hooks] El framework pre-commit gestiona el ADR gate — nada que instalar."
  exit 0
fi

if [[ -f "$COMMIT_MSG_HOOK" ]] && ! _has_line "$COMMIT_MSG_HOOK" "$BANNER"; then
  # Hook de otro sistema — preservarlo y (re)poner nuestro bloque al final
  if [ "$(_block_of "$COMMIT_MSG_HOOK")" != "$GATE_BODY" ]; then
    _backup "$COMMIT_MSG_HOOK"
    _has_line "$COMMIT_MSG_HOOK" "$BLOCK_BEGIN" && _strip_block "$COMMIT_MSG_HOOK"
    {
      echo "$BLOCK_BEGIN"
      echo "$GATE_BODY"
      echo "$BLOCK_END"
    } >> "$COMMIT_MSG_HOOK"
    echo "[ai-tooling:hooks] Agregado al hook existente: $COMMIT_MSG_HOOK"
    echo "[ai-tooling:hooks] WARN: verifica que el comportamiento combinado sea correcto."
  fi
elif [ "$CODE" != "10" ]; then
  _backup "$COMMIT_MSG_HOOK"
  printf '%s\n' "$HOOK_FILE_CONTENT" > "$COMMIT_MSG_HOOK"
  chmod +x "$COMMIT_MSG_HOOK"
  echo "[ai-tooling:hooks] Instalado: $COMMIT_MSG_HOOK"
fi

echo "[ai-tooling:hooks] ADR gate activo en cada commit (commit-msg)."
exit 0
